// Builds content/OWNER-CONFIRM.md from the pages that were actually built, so
// the list can never drift from what is on the site.
//
// Every open question is rendered by src/components/ConfirmNote.astro, which
// marks itself with data-confirm. That is the only thing this script looks for,
// so a note added anywhere on the page is picked up without touching this file.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'

const MARKER = '[OWNER TO CONFIRM]'
const PAGES = [{ file: 'dist/index.html', route: '/', label: 'All Services' }]

const strip = (html) =>
  html
    .replace(/<svg[\s\S]*?<\/svg>/g, '')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&#39;/g, "'")
    .replace(/&#8217;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()

/** The heading the note sits under, or the FAQ question it belongs to. */
function contextFor(before) {
  const summaries = [...before.matchAll(/<summary[^>]*>([\s\S]*?)<\/summary>/g)]
  const lastSummary = summaries[summaries.length - 1]
  if (lastSummary) {
    const afterSummary = before.slice(lastSummary.index)
    // Still inside that details element if it has not been closed yet.
    if (!afterSummary.includes('</details>')) return strip(lastSummary[1])
  }

  const headings = [...before.matchAll(/<h[23][^>]*>([\s\S]*?)<\/h[23]>/g)]
  const lastHeading = headings[headings.length - 1]
  return lastHeading ? strip(lastHeading[1]) : 'On the page'
}

/** The sentence the note is attached to, so the owner can see what it qualifies.
    Earlier notes are removed first, or a run of them reads as one long sentence. */
function sentenceFor(before) {
  const withoutNotes = before.replace(/<p[^>]*\bdata-confirm\b[^>]*>[\s\S]*?<\/p>/g, ' ')

  // Prefer the last self contained block, which is the line the note qualifies.
  const blocks = [...withoutNotes.matchAll(/<(?:li|p|h3|span)[^>]*>([\s\S]*?)<\/(?:li|p|h3|span)>/g)]
  for (let index = blocks.length - 1; index >= 0; index -= 1) {
    const text = strip(blocks[index][1])
    if (text.length >= 12 && text.length <= 300) return text
  }

  const text = strip(withoutNotes)
  return text ? text.slice(-200).replace(/^\S*\s/, '') : ''
}

const sections = []
let total = 0

for (const page of PAGES) {
  if (!existsSync(page.file)) continue
  const html = readFileSync(page.file, 'utf8')
  const items = []

  for (const match of html.matchAll(/<p[^>]*\bdata-confirm\b[^>]*>([\s\S]*?)<\/p>/g)) {
    const ask = strip(match[1]).replace(MARKER, '').trim()
    if (!ask) continue
    const before = html.slice(0, match.index)
    items.push({ context: contextFor(before), sentence: sentenceFor(before), ask })
  }

  if (items.length) {
    total += items.length
    sections.push({ ...page, items })
  }
}

const lines = [
  '# Owner confirmations needed',
  '',
  'Each item below is published on the live page with an `' + MARKER + '` note next to it.',
  'Send the answers back, we drop them into the copy, and the note disappears.',
  '',
  '**Please clear these before the page is linked from the main kleaner.my menu.**',
  '',
  `Total open items: **${total}**`,
  '',
  'This file is generated by `npm run build`. Do not edit it by hand.',
  '',
  '---',
  '',
]

for (const section of sections) {
  lines.push(`## ${section.label} (\`${section.route}\`)`, '')
  lines.push(`${section.items.length} open item${section.items.length === 1 ? '' : 's'}.`, '')

  section.items.forEach((item, index) => {
    lines.push(`### ${index + 1}. ${item.context}`, '')
    lines.push('**What we need from you**', '')
    lines.push(`> ${item.ask}`, '')
    if (item.sentence) {
      lines.push('**Where it sits on the page**', '')
      lines.push(`> ${item.sentence}`, '')
    }
    lines.push('**Your answer:** _______________________________________________', '')
  })

  lines.push('---', '')
}

lines.push(
  '## How to clear an item',
  '',
  '1. Reply with the answer.',
  '2. We edit the matching entry, removing the `confirm:` line and folding the fact',
  '   into the sentence above it. Services live in `src/data/services.ts`; the rest',
  '   of the page reads from `src/data/copy/services.en.ts`.',
  '3. Run `npm run build` and this file regenerates itself with the item gone.',
  '',
  '## Why the notes are visible on the page',
  '',
  'They are deliberately loud so nothing unverified goes live unnoticed. They are kept out of the',
  'FAQ structured data, and any FAQ question carrying one is left out of it entirely, so Google',
  'never sees a placeholder answer. `npm run verify` checks that.',
  ''
)

mkdirSync('content', { recursive: true })
writeFileSync('content/OWNER-CONFIRM.md', lines.join('\n'))
console.log(`wrote content/OWNER-CONFIRM.md with ${total} open items`)
